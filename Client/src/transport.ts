import { createClient, SupabaseClient } from '@supabase/supabase-js';
import { Capacitor } from '@capacitor/core';
import { App as NativeApp } from '@capacitor/app';
import { Browser } from '@capacitor/browser';
import { NATIVE_CALLBACK, oauthCallback, publicConfig } from './auth-utils';
export interface Profile { id: string; avatar_path?: string; username: string; name: string; university?:string; program?:string; bio?:string; interests?:string }
export interface Chat { id: string; kind: 'direct' | 'group'; title: string; owner: string; created_at: string }
export interface Message { id: number; conversation_id: string; sender_id: string; body: string; created_at: string }
export interface Friendship { id: string; sender: string; recipient: string; status: 'pending' | 'accepted' }
export interface Membership { conversation_id: string; user_id: string }
export class MessengerApi {
  client!: SupabaseClient;
  private callbackCodes = new Set<string>();
  private nativeListener?: Awaited<ReturnType<typeof NativeApp.addListener>>;
  redirectUrl() { return Capacitor.isNativePlatform() ? NATIVE_CALLBACK : new URL('.',location.href).href; }
  configure(url: string, key: string) {
    const config=publicConfig(url,key);
    this.client = createClient(config.url, config.key, { auth: { flowType:'pkce',persistSession: true, autoRefreshToken: true, detectSessionInUrl: false } });
    localStorage.setItem('warmly.public-config', JSON.stringify(config));
  }
  async google() {
    const native=Capacitor.isNativePlatform();
    const {data,error}=await this.client.auth.signInWithOAuth({provider:'google',options:{redirectTo:this.redirectUrl(),skipBrowserRedirect:true,queryParams:{prompt:'select_account'}}});
    if(error)throw error;
    if(!data.url)throw new Error('Google sign-in could not be started. Please try again.');
    // The URL is generated by the configured Supabase client, not an arbitrary redirect parameter.
    if(native)await Browser.open({url:data.url});else location.assign(data.url);
  }
  async finishOAuth(raw:string) {
    const callback=oauthCallback(raw,this.redirectUrl());
    if(!callback)return false;
    if(!Capacitor.isNativePlatform())history.replaceState(null,'',new URL('.',location.href).pathname);
    if(callback.error)throw new Error(callback.error==='access_denied'?'Sign-in was cancelled. You can try again.':'This sign-in link could not be completed. Sign in with your email and password, or continue with Google.');
    if(this.callbackCodes.has(callback.code!))return false;
    this.callbackCodes.add(callback.code!);
    const {error}=await this.client.auth.exchangeCodeForSession(callback.code!);
    if(error)throw new Error('This link has expired, was already used, or was opened in another browser. If you confirmed your email, sign in with your email and password. You can also continue with Google.');
    if(Capacitor.isNativePlatform())await Browser.close().catch(()=>{});
    return true;
  }
  async watchNativeCallback(callback:(url:string)=>void) {
    if(!Capacitor.isNativePlatform())return;
    await this.nativeListener?.remove();
    this.nativeListener=await NativeApp.addListener('appUrlOpen',event=>callback(event.url));
    const launch=await NativeApp.getLaunchUrl();if(launch?.url)callback(launch.url);
  }
  async rpc(action: string, payload = {}): Promise<any> {
    const {data,error} = await this.client.rpc('messenger', {action,payload});
    if (error) throw new Error(error.message.includes('Could not find') ? 'Apply the messenger SQL migration in Supabase first.' : error.message);
    return data;
  }
  async table<T>(name: string): Promise<T[]> {
    const {data,error} = await this.client.from(name).select('*');
    if (error) throw new Error(error.message);
    return data as T[];
  }
}
